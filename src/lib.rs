/// The rbatis engine ([`RBatis`]) and its connection/transaction types.
///
/// An [`RBatis`] owns the connection pool, the interceptors and the id generator.
/// Create one, link it to a database, then run SQL with it:
///
/// ```rust,no_run
/// use rbatis::RBatis;
///
/// #[tokio::main]
/// async fn main() -> rbatis::Result<()> {
///     let rb = RBatis::new();
///     // `link` = `init` + check that a connection can be acquired
///     rb.link(rbdc_sqlite::SqliteDriver {}, "sqlite://target/sqlite.db").await?;
///     Ok(())
/// }
/// ```
///
/// `&rb` is itself a [`crate::Executor`], so it can be passed straight to
/// `crud!` methods and to `#[py_sql]`/`#[html_sql]`/`#[sql]` functions. Use
/// [`RBatis::acquire`] when several statements should share one connection, and
/// [`RBatis::acquire_begin`] when they should run inside a transaction.
pub mod rbatis;
