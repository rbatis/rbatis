//!
//! # API guide
//!
//! The pages below are the entry points for the runtime API. Most users only need
//! [`RBatis`] (the engine) plus the `crud!` macro.
//!
//! | Module | What you find there |
//! |--------|---------------------|
//! | [`rbatis`] | [`RBatis`]: create the engine, `init`/`link` a driver, acquire connections and transactions |
//! | [`executor`] | [`Executor`] and [`RBatisRef`]: every handle that can run SQL (`RBatis`, [`RBatisConnExecutor`], [`RBatisTxExecutor`], [`RBatisTxExecutorGuard`]) |
//! | [`mod@crud`] | the [`crud!`] macro, which generates `insert`, `insert_batch`, `select_by_map`, `update_by_map`, `delete_by_map` for a struct |
//! | [`crud_traits`] | small traits used by the generated CRUD code |
//! | [`plugin`] | pagination ([`plugin::page`]), SQL interceptors ([`plugin::intercept`]), distributed ID generators ([`plugin::id_generator`]) and table sync ([`plugin::table_sync`]) |
//! | [`mod@decode`] | decode `rbs::Value` rows into your own `serde` types ([`decode()`], [`decode_ref()`]) |
//! | [`error`] | [`Error`] and [`Result`] used by every API of this crate |
//! | [`utils`] | helper macros: [`field_name!`], [`field_key!`], [`table!`], [`table_field_vec!`], [`table_field_map!`], [`table_field_set!`], [`table_field_btree!`] |
//!
//! Attribute macros live in this crate root as well: [`py_sql`], [`html_sql`] and
//! [`sql`] turn a function body into an executable SQL statement at compile time,
//! [`impled!`] is the placeholder body used together with them.
//!
//! # Feature flags
//!
//! | Feature | Default | Effect |
//! |---------|---------|--------|
//! | `default` | yes | enables the procedural macro driver, so `#[py_sql]`, `#[html_sql]`, `#[sql]`, `crud!`, `table!` ... are available |
//! | `debug_mode` | no | prints the JSON rows returned by the database and the generated dynamic SQL code to the `log`/`fast_log` output. They are printed with the `debug` log level, so a logger must be initialized with `LevelFilter::Debug` |
//! | `println_gen` | no | prints the Rust code generated by `#[py_sql]`/`#[html_sql]` at compile time (useful when debugging a query) |
//! | `upper_case_sql_keyword` | no | reserved; currently a no-op |
//!
